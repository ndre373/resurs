/**
 * gen-sw-assets.mjs — runs AFTER `vite build` (see deploy.yml): scans
 * dist/public and writes sw-assets.js with the full file list. The service
 * worker precaches every one of them at install time, so the app is fully
 * offline from the very first visit — including the lazily loaded 3D scenes.
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, relative } from "node:path";

const root = fileURLToPath(new URL("../dist/public", import.meta.url));

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(relative(root, p).replaceAll("\\", "/"));
  }
  return out;
}

// sw.js caches itself indirectly; 404.html is the SPA fallback — same bytes
// as index.html, no need to store twice
const files = walk(root).filter((f) => !["sw.js", "sw-assets.js", "404.html"].includes(f));
const list = ["./", ...files];

writeFileSync(
  join(root, "sw-assets.js"),
  `/* generated by scripts/gen-sw-assets.mjs — do not edit */\nself.SW_ASSETS = ${JSON.stringify(list)};\n`,
);
console.log(`sw-assets.js: ${list.length} files precached`);
